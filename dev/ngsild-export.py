#!/usr/bin/env python3
"""Export the five NGSI-LD crates as a standalone Cargo workspace (T-3913).

The crates live and are developed here; github.com/marek-mraz-jc/ngsild is where other projects
take them from, as a git dependency at a v* tag (owner decision 2026-10-18: no crates.io for
now). This writes that repository's tree from the current checkout:

    python3 dev/ngsild-export.py <out-dir>      # out-dir must not exist or be empty

then, in a clone of marek-mraz-jc/ngsild: replace everything but .git with <out-dir>, commit
"ngsild <version> from Antares <commit>", tag v<version>, push both. The tag's workflow there
tests the workspace and attests provenance on the release (dev/ngsild-repo/.github/workflows).

What goes over: the crate folders (minus the tests and examples that read the vendored ETSI
suite, which stays here), a root Cargo.toml holding only the workspace entries those crates
inherit, Cargo.lock (pruned to
what the five use, same versions), LICENSE, the toolchain
pin, the two documents a jsonld test checks the egress default against, and dev/ngsild-repo/.
"""

import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CRATES = ["antares-model", "antares-jsonld", "antares-ql", "antares-matcher", "antares-residual"]
REPOSITORY = "https://github.com/marek-mraz-jc/ngsild"
# read by crates/antares-jsonld/src/loader.rs the_documented_egress_default_is_the_compiled_one
FILES = ["LICENSE", "rust-toolchain.toml", "Cargo.lock", "SECURITY.md", "docs/src/configuration.md"]
SUITE = "ngsi-ld-test-suite"


def toml_value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(v, list):
        return "[" + ", ".join(toml_value(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{toml_key(k)} = {toml_value(x)}" for k, x in v.items()) + " }"
    raise TypeError(f"no TOML form for {v!r}")


def toml_key(k):
    return k if k.replace("-", "").replace("_", "").isalnum() else toml_value(k)


def table(name, entries):
    return [f"[{name}]"] + [f"{toml_key(k)} = {toml_value(v)}" for k, v in entries.items()] + [""]


def inherited(manifest):
    """Names of the workspace dependencies a crate manifest takes with `workspace = true`."""
    sections = [manifest.get(s, {}) for s in ("dependencies", "dev-dependencies", "build-dependencies")]
    for target in manifest.get("target", {}).values():
        sections += [target.get(s, {}) for s in ("dependencies", "dev-dependencies", "build-dependencies")]
    return {n for s in sections for n, d in s.items() if isinstance(d, dict) and d.get("workspace")}


def reads_suite(path):
    """A test or example that reads the vendored ETSI suite, which is not exported."""
    return (path.parent.name in ("tests", "examples") and path.suffix == ".rs"
            and SUITE in path.read_text(encoding="utf-8"))


def export(out):
    if out.exists() and any(out.iterdir()):
        sys.exit(f"{out}: not empty")
    root = tomllib.loads((ROOT / "Cargo.toml").read_text(encoding="utf-8"))
    ws = root["workspace"]
    deps = ws["dependencies"]
    used = set()
    for c in CRATES:
        used |= inherited(tomllib.loads((ROOT / "crates" / c / "Cargo.toml").read_text(encoding="utf-8")))
    missing = used - deps.keys()
    if missing:
        sys.exit(f"inherited but not in [workspace.dependencies]: {sorted(missing)}")
    for name in used:
        path = deps[name].get("path") if isinstance(deps[name], dict) else None
        if path and Path(path).name not in CRATES:
            sys.exit(f"{name}: path dependency {path} is not one of the exported crates")

    for c in CRATES:
        src = ROOT / "crates" / c
        shutil.copytree(src, out / "crates" / c,
                        ignore=lambda d, names: [n for n in names if reads_suite(Path(d) / n)])
    for f in FILES:
        (out / f).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / f, out / f)
    shutil.copytree(ROOT / "dev" / "ngsild-repo", out, dirs_exist_ok=True)

    commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, check=True,
                            capture_output=True, text=True).stdout.strip()
    package = dict(ws["package"], repository=REPOSITORY)
    lines = [
        f"# Generated by dev/ngsild-export.py from Antares-NGSI-LD-Context-Broker {commit}.",
        "# Change the crates there; this repository only carries released copies.",
        "[workspace]",
        'resolver = "2"',
        "members = " + toml_value([f"crates/{c}" for c in CRATES]),
        "",
        *table("workspace.package", package),
        *table("workspace.dependencies", {n: deps[n] for n in sorted(used)}),
    ]
    for tool, lints in ws.get("lints", {}).items():
        lines += table(f"workspace.lints.{tool}", lints)
    (out / "Cargo.toml").write_text("\n".join(lines), encoding="utf-8")
    (out / "SOURCE").write_text(f"{commit}\n", encoding="utf-8")
    # drop the lock entries only the rest of Antares needs; every version stays as tested here
    subprocess.run(["cargo", "metadata", "--format-version", "1", "--offline"], cwd=out, check=True,
                   stdout=subprocess.DEVNULL)
    print(f"ngsild {package['version']} from {commit} -> {out}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    export(Path(sys.argv[1]))
