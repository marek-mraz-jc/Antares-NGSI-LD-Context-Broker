"""A new read-only surface as a crate of its own, wired into the broker (T-5063,
docs/src/new-surface.md).

    dev/new-surface.py NAME --title "GeoJSON of a view" --description "…" [--struct GeoJson]

writes crates/antares-NAME (Cargo.toml, src/lib.rs, tests/NAME.rs), docs/src/NAME.md and
tests/NAME/README.md from dev/new-surface/*.in, and adds the crate to the workspace, the
broker feature NAME, the SURFACE_SHELF entry, ARCHITECTURE.md, the book's summary, the surfaces table and the
vanilla-build gate. The crate depends on antares-ops alone, so it reaches data only through
the policy seam (module rule M2); its generated tests pass as written. A surface then writes
its `render` and the standard's rows of the pack. Every edit anchors on one line of the file
it edits and the script refuses before writing anything when an anchor is missing.

    dev/new-surface.py --self-test   generate into a copy of the tree's text files and check it
"""

import argparse
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
TEMPLATE = ROOT / "dev/new-surface"
NAME = re.compile(r"[a-z][a-z0-9]{1,15}")
TOUCHED = (
    "Cargo.toml",
    "crates/antares-broker/Cargo.toml",
    "crates/antares-broker/src/main.rs",
    "ARCHITECTURE.md",
    "docs/src/SUMMARY.md",
    "docs/src/surfaces.md",
    "dev/check-no-addon.sh",
)


def after_last(text, pattern, insert, block=False):
    """`text` with `insert` after the last line matching `pattern`, or with `block` after the
    blank line that ends the TOML table that line opens."""
    lines = text.splitlines(keepends=True)
    hits = [i for i, line in enumerate(lines) if re.match(pattern, line)]
    if not hits:
        raise SystemExit(f"anchor {pattern!r} not found")
    at = hits[-1] + 1
    if block:
        at = next((i + 1 for i in range(at, len(lines)) if not lines[i].strip()), len(lines))
    lines.insert(at, insert)
    return "".join(lines)


def before_one(text, anchor, insert):
    """`text` with `insert` before `anchor`, which must occur exactly once."""
    if text.count(anchor) != 1:
        raise SystemExit(f"anchor {anchor!r} occurs {text.count(anchor)} times, not once")
    return text.replace(anchor, insert + anchor)


def edits(name, struct, title, desc):
    """Each touched file's edit, a function of its text."""
    crate = f"antares-{name}"
    return {
        "Cargo.toml": lambda t: after_last(
            after_last(
                after_last(t, r'    "crates/antares-[a-z0-9]+",$', f'    "crates/{crate}",\n'),
                r'antares-[a-z0-9]+ = \{ path = "crates/antares-[a-z0-9]+" \}$',
                f'{crate} = {{ path = "crates/{crate}" }}\n',
            ),
            r"\[profile\.release\.package\.antares-[a-z0-9]+\]$",
            f"[profile.release.package.{crate}]\noverflow-checks = true\ncodegen-units = 1\n\n",
            block=True,
        ),
        "crates/antares-broker/Cargo.toml": lambda t: after_last(
            after_last(
                t,
                r"antares-[a-z0-9]+ = \{ workspace = true, optional = true \}$",
                f"{crate} = {{ workspace = true, optional = true }}\n",
            ),
            r'[a-z0-9-]+ = \["views", "dep:antares-[a-z0-9]+"\]$',
            f"\n# `/x/views/{{view}}/{name}/v1/{{type}}`, {title}, read only, generated by\n"
            f"# dev/new-surface.py (`ANTARES_API_SURFACES=admin,views,{name}`).\n"
            f'{name} = ["views", "dep:{crate}"]\n',
        ),
        "crates/antares-broker/src/main.rs": lambda t: before_one(
            t,
            '    #[cfg(feature = "ws")]\n    ("ws", ',
            f'    #[cfg(feature = "{name}")]\n'
            f'    ("{name}", || antares_ops::mount(antares_{name}::{struct})),\n',
        ),
        "ARCHITECTURE.md": lambda t: after_last(
            t,
            r"\| `antares-[a-z0-9]+` \|.*role surface",
            f"| `{crate}` | {title} `/x/views/{{view}}/{name}/v1/{{type}}` (role surface, feature "
            f"`{name}`, generated by `dev/new-surface.py`): {desc} | name the store, the policy "
            "engine or any crate but `antares-ops`; read around the view; write |\n",
        ),
        "docs/src/SUMMARY.md": lambda t: before_one(
            t, "- [WebSocket notifications](websocket.md)\n", f"- [{title}]({name}.md)\n"
        ),
        "docs/src/surfaces.md": lambda t: after_last(
            t,
            r"\| [^|]+ \| `[a-z0-9-]+` \(adds `views`\) \| `[a-z0-9-]+` \| `/x/views/\{view\}/",
            f"| {title} | `{name}` (adds `views`) | `{name}` | `/x/views/{{view}}/{name}/v1/{{type}}` "
            f"| [{title}]({name}.md) |\n",
        ),
        "dev/check-no-addon.sh": lambda t: before_one(t, "antares-ops|", f"{crate}|"),
    }


def generate(root, name, struct, title, desc):
    """Write the crate, its docs and pack under `root` and wire them in; return what changed."""
    if not NAME.fullmatch(name):
        raise SystemExit(f"{name!r}: a name is 2 to 16 of a-z and 0-9, starting with a letter")
    if not re.fullmatch(r"[A-Z][A-Za-z0-9]*", struct):
        raise SystemExit(f"{struct!r}: the struct is a Rust type name")
    if "\n" in title + desc or "|" in title + desc:
        raise SystemExit("the title and description are one line without '|'")
    crate_dir = root / f"crates/antares-{name}"
    shelf = (root / "crates/antares-broker/src/main.rs").read_text()
    if crate_dir.exists() or f'("{name}",' in shelf:
        raise SystemExit(f"a surface named {name} exists already")
    new = {f: fn((root / f).read_text()) for f, fn in edits(name, struct, title, desc).items()}

    def fill(template):
        text = (TEMPLATE / template).read_text()
        for key, value in {
            "@CRATE@": f"antares_{name}",
            "@STRUCT@": struct,
            "@TITLE@": title,
            "@DESC@": desc,
            "@NAME@": name,
        }.items():
            text = text.replace(key, value)
        return text

    files = {
        f"crates/antares-{name}/Cargo.toml": fill("Cargo.toml.in"),
        f"crates/antares-{name}/src/lib.rs": fill("lib.rs.in"),
        f"crates/antares-{name}/tests/{name}.rs": fill("surface_test.rs.in"),
        f"docs/src/{name}.md": fill("doc.md.in"),
        f"tests/{name}/README.md": fill("pack.md.in"),
        **new,
    }
    for rel, text in files.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return sorted(files)


def self_test():
    """Generate `probe` into a copy of the touched files and templates; check every edit."""
    with tempfile.TemporaryDirectory() as tmp:
        root = pathlib.Path(tmp)
        for rel in TOUCHED:
            (root / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy(ROOT / rel, root / rel)
        written = generate(root, "probe", "Probe", "Probe of a view", "the probe.")
        assert len(written) == 5 + len(TOUCHED), written
        cargo = (root / "Cargo.toml").read_text()
        assert '    "crates/antares-probe",\n' in cargo
        assert 'antares-probe = { path = "crates/antares-probe" }' in cargo
        assert "[profile.release.package.antares-probe]\noverflow-checks = true\ncodegen-units = 1\n" in cargo
        broker = (root / "crates/antares-broker/Cargo.toml").read_text()
        assert '"]\n\n# `/x/views/{view}/probe/v1/{type}`, Probe of a view' in broker
        assert 'probe = ["views", "dep:antares-probe"]\n' in broker
        assert "antares-probe = { workspace = true, optional = true }" in broker
        main = (root / "crates/antares-broker/src/main.rs").read_text()
        assert '("probe", || antares_ops::mount(antares_probe::Probe)),\n    #[cfg(feature = "ws")]' in main
        assert "| [Probe of a view](probe.md) |\n| WebSocket" in (root / "docs/src/surfaces.md").read_text()
        assert "antares-probe|antares-ops|" in (root / "dev/check-no-addon.sh").read_text()
        lib = (root / "crates/antares-probe/src/lib.rs").read_text()
        assert "@" not in re.sub(r"@context", "", lib), "a placeholder is left"
        for bad in ("Probe", "probe-x", "p", "x" * 17):
            try:
                generate(root, bad, "Probe", "t", "d")
            except SystemExit:
                continue
            raise AssertionError(f"{bad!r} was accepted")
        try:
            generate(root, "probe", "Probe", "t", "d")
            raise AssertionError("a second probe was accepted")
        except SystemExit:
            pass
    print("new-surface self-test: OK")


def main():
    if sys.argv[1:] == ["--self-test"]:
        self_test()
        return
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("name")
    parser.add_argument("--title", required=True, help='the book title, e.g. "GeoJSON of a view"')
    parser.add_argument("--description", required=True, help="one sentence: what the surface serves")
    parser.add_argument("--struct", help="the Rust type, default the capitalised name")
    args = parser.parse_args()
    struct = args.struct or args.name.capitalize()
    for rel in generate(ROOT, args.name, struct, args.title, args.description):
        print(f"wrote {rel}")
    subprocess.run(["cargo", "fmt", "-p", f"antares-{args.name}"], cwd=ROOT, check=True)
    print(
        f"next: write render() in crates/antares-{args.name}/src/lib.rs and the standard's rows of\n"
        f"tests/{args.name}/README.md; cargo test -p antares-{args.name}; then the gateway's\n"
        "Representation and route in joinedcontext-platform (docs/src/new-surface.md section 3)."
    )


if __name__ == "__main__":
    main()
